import Link from 'next/link';
import { CodeBlock } from '@/components/ui';
import {
  PLACEHOLDER_ROLE_ARN,
  PLACEHOLDER_USER_ARN,
  assumePolicy,
  permissionsPolicy,
  trustPolicy,
} from '@/lib/dns/aws-policy';
import { Callout } from '../../_lib/prose';

const json = (doc: unknown) => JSON.stringify(doc, null, 2);
const EXAMPLE = { userArn: PLACEHOLDER_USER_ARN, roleArn: PLACEHOLDER_ROLE_ARN };

export default function AwsProvider() {
  return (
    <>
      <h1>AWS provider</h1>
      <p className="lead">
        A provider is an identity on an AWS account that local-cert uses to read and write in
        Route53. You create one per account — <code>aws-prod</code>, <code>aws-lab</code> — then
        declare your domains on it.
      </p>

      <h2>The model</h2>
      <p>Three objects on the AWS side, each with a precise role:</p>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Object</th>
              <th>Role</th>
              <th>What it carries</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>IAM user</td>
              <td>local-cert&apos;s identity</td>
              <td>a key pair, and nothing else</td>
            </tr>
            <tr>
              <td>IAM role</td>
              <td>what local-cert is allowed to do</td>
              <td>the Route53 policy, which you extend over time</td>
            </tr>
            <tr>
              <td>Role policy</td>
              <td>the list of allowed zones</td>
              <td>generated by local-cert, pasted by you</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p>
        The key stored in local-cert therefore grants no permission by itself: it only lets you
        assume the role. Adding a zone means editing the role&apos;s policy; the key never changes.
      </p>
      <p>
        The wizard on the <Link href="/admin/providers">Providers</Link> page walks through these
        steps and generates each document with your real identifiers. This guide explains them in
        detail.
      </p>

      <h2>1. Create the IAM user</h2>
      <ol>
        <li>
          AWS console → <b>IAM</b> → <b>Users</b> → <b>Create user</b>.
        </li>
        <li>
          Name: <code>local-cert</code>. Leave{' '}
          <i>Provide user access to the AWS Management Console</i> unchecked.
        </li>
        <li>
          On the permissions step, <b>attach nothing</b>. Finish creating the user.
        </li>
        <li>
          Open the user → <b>Security credentials</b> → <b>Create access key</b> → use case{' '}
          <i>Application running outside AWS</i>.
        </li>
        <li>
          Note the <b>Access key ID</b> and the <b>Secret access key</b>: the latter can&apos;t be
          viewed again afterwards.
        </li>
      </ol>

      <h2>2. Enter the key in local-cert</h2>
      <ol>
        <li>
          <Link href="/admin/providers">Providers</Link> → <b>+ New provider</b>.
        </li>
        <li>
          Give it a name (<code>aws-prod</code>) and paste the key pair.
        </li>
        <li>
          <b>Check the key</b>: local-cert calls <code>sts:GetCallerIdentity</code>, which needs no
          permission, and displays the user&apos;s ARN. That ARN is used to generate what follows.
        </li>
      </ol>
      <p>
        The secret key is encrypted in the database (AES-256-GCM with <code>MASTER_KEY</code>) and
        is never displayed again or returned by the API.
      </p>

      <h2>3. Create the role</h2>
      <ol>
        <li>
          <b>IAM</b> → <b>Roles</b> → <b>Create role</b> → <b>Custom trust policy</b>.
        </li>
        <li>
          Paste the <b>trust policy</b> shown by the wizard. It lets only your user assume the
          role:
        </li>
      </ol>
      <CodeBlock title="Trust policy (example)" code={json(trustPolicy(PLACEHOLDER_USER_ARN))} />
      <ol start={3}>
        <li>
          On the permissions step, don&apos;t add any managed policy.
        </li>
        <li>
          Role name: <code>local-cert-dns</code>. Create it.
        </li>
        <li>
          Open the role → <b>Permissions</b> → <b>Add permissions</b> →{' '}
          <b>Create inline policy</b> → <b>JSON</b> tab, and paste the wizard&apos;s{' '}
          <b>permissions policy</b>. At this point it only contains what is needed to list zones:
        </li>
      </ol>
      <CodeBlock title="Initial permissions policy" code={json(permissionsPolicy([], EXAMPLE))} />
      <ol start={6}>
        <li>
          Name the policy (<code>local-cert-route53</code>), save it, then copy the{' '}
          <b>role ARN</b> into the wizard.
        </li>
      </ol>

      <h2>4. Test and save</h2>
      <p>
        <b>Test connection</b> runs three checks in sequence, each depending on the previous one:
      </p>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Check</th>
              <th>If it fails</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>Key pair</td>
              <td>unknown, disabled or mistyped key</td>
            </tr>
            <tr>
              <td>Role (AssumeRole)</td>
              <td>wrong role ARN, or a trust policy that doesn&apos;t name the right user</td>
            </tr>
            <tr>
              <td>Zones (ListHostedZones)</td>
              <td>permissions policy missing from the role, or not yet propagated</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p>
        IAM applies a change within a few seconds: a test run right after pasting may fail once.
        When all three lines show <code>OK</code>, click <b>Save</b>.
      </p>

      <h2>5. Add domains</h2>
      <p>
        The provider can now list your zones, but is not yet allowed to write to any of them.
        Those permissions are added zone by zone:{' '}
        <Link href="/admin/docs/domains">Add a domain</Link>. Once a few zones are declared, the
        role&apos;s policy looks like this:
      </p>
      <CodeBlock
        title="Permissions policy with two zones (example)"
        code={json(permissionsPolicy(['Z0123456ABCDEFGHIJK', 'Z0987654ZYXWVUTSRQP'], EXAMPLE))}
      />
      <p>
        Each provider&apos;s <b>policy</b> button regenerates this document at any time from the
        domains actually declared.
      </p>

      <h2>What the policy allows</h2>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Action</th>
              <th>Scope</th>
              <th>Why</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>
                <code>ListHostedZones</code>
              </td>
              <td>account</td>
              <td>offer the list of zones; AWS doesn&apos;t allow restricting it</td>
            </tr>
            <tr>
              <td>
                <code>GetChange</code>
              </td>
              <td>account</td>
              <td>wait until a write has propagated</td>
            </tr>
            <tr>
              <td>
                <code>GetHostedZone</code>, <code>ListResourceRecordSets</code>
              </td>
              <td>declared zones</td>
              <td>find the name servers to query, list records</td>
            </tr>
            <tr>
              <td>
                <code>ChangeResourceRecordSets</code>
              </td>
              <td>declared zones, TXT / A / AAAA types, UPSERT / DELETE actions</td>
              <td>
                write the validation TXT; publish a host&apos;s address if you ask for it
              </td>
            </tr>
            <tr>
              <td>
                <code>iam:ListAccessKeys</code>, <code>DeleteAccessKey</code>,{' '}
                <code>ListUserPolicies</code>, <code>DeleteUserPolicy</code>,{' '}
                <code>DeleteUser</code>
              </td>
              <td>the provider&apos;s IAM user, and only that user</td>
              <td>
                optional: delete it when the provider is removed (
                <a href="#nettoyage">cleanup</a>)
              </td>
            </tr>
            <tr>
              <td>
                <code>iam:ListRolePolicies</code>, <code>DeleteRolePolicy</code>
              </td>
              <td>the provider&apos;s role, and only that role</td>
              <td>optional: empty the role when the provider is removed</td>
            </tr>
          </tbody>
        </table>
      </div>
      <Callout kind="warn" title="If you edit the policy by hand">
        Two mistakes produce an <code>AccessDenied</code> that is hard to read: removing{' '}
        <code>TXT</code> from the allowed types (no issuance is possible any more), and writing two{' '}
        <code>Condition</code> blocks with the same operator (the JSON keeps only the last one).
        The safest approach is to paste the generated document back in full.
      </Callout>

      <h2>Multiple AWS accounts</h2>
      <p>Two ways to cover a second account, depending on what you want to isolate.</p>
      <h3>One provider per account</h3>
      <p>
        Repeat steps 1 to 4 in the other account and name the provider accordingly. Each account has
        its own key; revoking one doesn&apos;t affect the other. This is the easiest setup to
        reason about.
      </p>
      <h3>One key, one role per account</h3>
      <p>
        The user stays in account A; the role is created in account B, with the same trust policy
        (account A&apos;s user ARN). Across accounts, the user must also be allowed to assume that
        role. Attach this inline policy to it:
      </p>
      <CodeBlock
        title="User policy, cross-account case"
        code={json(assumePolicy(PLACEHOLDER_ROLE_ARN))}
      />
      <p>
        Then create a second provider with the same key pair and the ARN of account B&apos;s role.
      </p>

      <h2>Variants</h2>
      <h3>Without a role</h3>
      <p>
        Uncheck <i>Use an IAM role</i> in the wizard: the permissions policy is then pasted directly
        onto the user. That is one step fewer, at the cost of a key that carries the permissions
        itself.
      </p>
      <h3>Without a key</h3>
      <p>
        If local-cert runs inside AWS or in a cluster with IRSA, check <i>No key</i>: the provider
        uses the process credentials (instance role, pod role, environment variables). A role to
        assume is still possible on top of that.
      </p>

      <h2>Declaring a provider with environment variables</h2>
      <p>
        When credentials must come from the deployment rather than the database — secrets managed
        by the orchestrator, infrastructure described as code — a provider can be declared with
        variables. Everything is optional: with no variables at all, providers are managed from the
        console only.
      </p>
      <CodeBlock
        title=".env"
        code={`PROVIDER_AWS_DEFAULT_NAME="Default AWS"
PROVIDER_AWS_DEFAULT_ACCESS_KEY_ID=AKIA…
PROVIDER_AWS_DEFAULT_SECRET_ACCESS_KEY=…
PROVIDER_AWS_DEFAULT_ROLE_ARN=arn:aws:iam::123456789012:role/local-cert-dns

# a second account: same block, different label
PROVIDER_AWS_PROD_NAME="aws-prod"
PROVIDER_AWS_PROD_ACCESS_KEY_ID=AKIA…
PROVIDER_AWS_PROD_SECRET_ACCESS_KEY=…`}
      />
      <ul>
        <li>
          <code>_NAME</code> declares the provider; it is the only mandatory variable in the block.
          The label (<code>DEFAULT</code>, <code>PROD</code>…) is free.
        </li>
        <li>
          Without a key pair, the provider uses the process credentials. <code>_ROLE_ARN</code> and{' '}
          <code>_REGION</code> are optional.
        </li>
        <li>
          These providers appear in the console with an <i>environment</i> tag. They can be tested
          and their policy generated, but not edited or removed: that is done in the variables,
          followed by a restart. Their secret key is never written to the database.
        </li>
        <li>
          The <code>DEFAULT</code> label is special: domains declared before providers existed are
          attached to it at startup.
        </li>
      </ul>

      <h2 id="nettoyage">Removing a provider and cleaning up AWS</h2>
      <p>
        <Link href="/admin/providers">Providers</Link> → <b>Remove</b> deletes the provider from
        local-cert. If you check <b>Also clean up on AWS</b>, the provider first undoes what the
        wizard had you create:
      </p>
      <ol>
        <li>
          the role session deletes the IAM user: its access keys, its inline policies, then the
          user itself;
        </li>
        <li>it then deletes the role&apos;s own policy.</li>
      </ol>
      <p>
        IAM doesn&apos;t let an identity delete itself entirely: a role can only be deleted once
        its policies are gone, and the permission to do so comes from those policies. The{' '}
        <code>local-cert-dns</code> role therefore remains, with no permissions and nobody able to
        assume it. The console shows the command to delete it with an administrator account:
      </p>
      <CodeBlock title="AWS CLI" code="aws iam delete-role --role-name local-cert-dns" />
      <ul>
        <li>
          Without a role, the provider can only delete its own access key; the user remains, with
          no credentials.
        </li>
        <li>
          The matching permissions are the <code>LocalCertRemove…</code> blocks of the generated
          policy. They target only the provider&apos;s user and role and only allow deletion: a
          stolen key could shut local-cert down, not extend its permissions. Remove them from the
          document if you don&apos;t want this option.
        </li>
        <li>
          A provider created before this option existed must first receive the updated policy (
          <b>policy</b> button). If AWS refuses before anything is deleted, the provider is kept.
        </li>
        <li>
          The option isn&apos;t offered when another provider uses the same user or the same role,
          nor for providers declared with environment variables.
        </li>
        <li>
          If the user has managed policies attached or belongs to a group, IAM refuses to delete it:
          the cleanup stops there and lists what is left to do.
        </li>
      </ul>

      <h2>Key rotation</h2>
      <ol>
        <li>
          In IAM, create a <b>second</b> access key on the user.
        </li>
        <li>
          <Link href="/admin/providers">Providers</Link> → <b>Edit</b> →{' '}
          <i>Replace the key pair</i> → <b>Test</b>, then <b>Save</b>.
        </li>
        <li>In IAM, deactivate the old key, then delete it.</li>
      </ol>
      <p>The role and its policy are not affected.</p>
    </>
  );
}
