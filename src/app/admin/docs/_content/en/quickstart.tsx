import Link from 'next/link';
import { CodeBlock } from '@/components/ui';
import { Callout, EX, type DocCtx } from '../../_lib/prose';

export default function Quickstart({ ctx }: { ctx: DocCtx }) {
  return (
    <>
      <h1>Quick start</h1>
      <p className="lead">
        local-cert gets Let&apos;s Encrypt certificates for machines that can&apos;t be reached from
        the Internet: NAS boxes, hypervisors, internal services. Validation goes through DNS
        (DNS-01), so only local-cert needs access to your zone.
      </p>

      <h2>The full path</h2>
      <ol>
        <li>
          <b>Declare a DNS provider.</b> This is the account at the host of your zone, with its
          credentials: AWS, OVHcloud, Gandi, GoDaddy or Google Cloud. See the{' '}
          <Link href="/admin/providers">Providers</Link> page and the{' '}
          <Link href="/admin/docs/providers">DNS providers</Link> guides.
        </li>
        <li>
          <b>Add a domain.</b> Pick a zone from the provider; local-cert generates the IAM policy to
          paste, tests the permissions, then saves. See the{' '}
          <Link href="/admin/domains">Domains</Link> page and the{' '}
          <Link href="/admin/docs/domains">Add a domain</Link> guide.
        </li>
        <li>
          <b>Grant access.</b> In <Link href="/admin/keys">Keys &amp; access</Link>, create an{' '}
          <b>API key</b> (scripts, agents) or an <b>EAB credential</b> (ACME clients: Traefik,
          Caddy, certbot…), depending on what you need.
        </li>
        <li>
          <b>Issue.</b> Through the ACME server or the API — see below.
        </li>
      </ol>

      <h2>Which route to pick</h2>
      <div className="table-wrap">
        <table>
          <thead>
            <tr>
              <th></th>
              <th>ACME server</th>
              <th>REST API</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>For</td>
              <td>a reverse proxy or a tool that already speaks ACME</td>
              <td>a script, a tool without ACME, an agent (MCP)</td>
            </tr>
            <tr>
              <td>Access</td>
              <td>EAB credential</td>
              <td>API key</td>
            </tr>
            <tr>
              <td>Private key</td>
              <td>generated and kept by the client</td>
              <td>generated by local-cert, encrypted in the database</td>
            </tr>
            <tr>
              <td>Renewal</td>
              <td>by the client</td>
              <td>by local-cert (<code>auto_renew</code>)</td>
            </tr>
          </tbody>
        </table>
      </div>

      <h2>ACME route, in one command</h2>
      <p>
        With an EAB credential authorized on the domain, any ACME client can get a certificate.
        Example with certbot:
      </p>
      <CodeBlock
        title="certbot"
        code={`certbot certonly --standalone -d ${EX.host} \\
  --server ${ctx.directory} \\
  --eab-kid ${EX.kid} --eab-hmac-key ${EX.hmac}`}
      />
      <p>
        How it works, and the per-tool guides, are in{' '}
        <Link href="/admin/docs/acme">ACME server</Link>.
      </p>

      <h2>API route, in one request</h2>
      <CodeBlock
        title="curl"
        code={`curl -X POST ${ctx.origin}/api/v1/certificates \\
  -H "Authorization: Bearer $TOKEN" \\
  -H "Idempotency-Key: $(uuidgen)" \\
  -H 'content-type: application/json' \\
  -d '{
    "domains": ["${EX.host}"],
    "key_type": "ec-256",
    "auto_renew": true,
    "dns": { "create_record": true, "target_ip": "192.168.1.50" }
  }'`}
      />
      <p>
        The response is immediate (<code>202</code>); issuance takes one to three minutes. All
        routes are described under <Link href="/admin/api">API</Link>.
      </p>

      <Callout title="While testing">
        The <code>acme:staging</code> badge at the top of the console means local-cert is talking to
        Let&apos;s Encrypt&apos;s test environment: browsers won&apos;t trust the certificates, but
        you use no quota. Switch to production once the whole chain works.
      </Callout>
    </>
  );
}
